using System.Text;
using System.Text.Json;

namespace SkillSprintAI.Api.Services.GenAiPipeline;

public interface IGeminiGeneratorService
{
    Task<object> GenerateOnboardingPlanAsync(string role, List<object> documentChunks);
}

public class GeminiGeneratorService : IGeminiGeneratorService
{
    private readonly HttpClient _httpClient;
    private readonly string _apiKey;

    public GeminiGeneratorService(HttpClient httpClient, IConfiguration configuration)
    {
        _httpClient = httpClient;
        _apiKey = configuration["Gemini:ApiKey"] ?? "DEMO_KEY_ONLY";
    }

    public async Task<object> GenerateOnboardingPlanAsync(string role, List<object> documentChunks)
    {
        // In a real scenario, map this to proper structured request for Gemini
        var requestBody = new
        {
            contents = new[]
            {
                new
                {
                    parts = new[]
                    {
                        new { text = $"You are an HR onboarding AI. Create a plan for role: {role}. Data chunks: {JsonSerializer.Serialize(documentChunks)}. Reply in JSON." }
                    }
                }
            },
            generationConfig = new
            {
                response_mime_type = "application/json"
            }
        };

        var content = new StringContent(JsonSerializer.Serialize(requestBody), Encoding.UTF8, "application/json");
        var response = await _httpClient.PostAsync($"https://generativelanguage.googleapis.com/v1beta/models/gemini-1.5-pro:generateContent?key={_apiKey}", content);

        if (!response.IsSuccessStatusCode)
        {
            throw new Exception($"Gemini API error: {response.StatusCode} - {await response.Content.ReadAsStringAsync()}");
        }

        var responseJson = await response.Content.ReadAsStringAsync();
        
        // Simplified parse to extract the JSON output generated by Gemini
        // In production, map properly using classes
        var geminiResponse = JsonSerializer.Deserialize<JsonElement>(responseJson);
        var textContent = geminiResponse.GetProperty("candidates")[0].GetProperty("content").GetProperty("parts")[0].GetProperty("text").GetString();

        return JsonSerializer.Deserialize<object>(textContent ?? "{}");
    }
}
